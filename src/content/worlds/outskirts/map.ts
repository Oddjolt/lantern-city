const ROOMS = [WAKEFIELD, CHIMNEY, HALL, THORNBED, BASIN, SHRINE, STEPS, STATION];

/** Place the rooms side by side. Rows are padded to their room's widest row, so ragged edits are safe. */
function joinRooms(rooms: string[][]): string[] {
  const height = Math.max(...rooms.map((r) => r.length));
  const widths = rooms.map((r) => Math.max(...r.map((row) => row.length)));
  return Array.from({ length: height }, (_, y) => rooms.map((r, i) => (r[y] ?? '').padEnd(widths[i], ' ')).join(''));
}

export const OUTSKIRTS_MAP = joinRooms(ROOMS);
