// ---- the train (drawn with code: rectangles and circles) --------------------------------
function train(wheelPhase: number): string[] {
  const b = new PixelBuffer(128, 44);
  b.rect(6, 2, 116, 4, 2); // roof
  b.rect(8, 1, 112, 1, 3);
  b.rect(3, 6, 122, 26, 1); // body
  b.rect(3, 6, 122, 1, 2);
  b.rect(3, 31, 122, 1, 2);
  b.rect(3, 6, 1, 26, 2);
  b.rect(124, 6, 1, 26, 2);
  for (let i = 0; i < 5; i++) {
    const x = 10 + i * 20;
    b.rect(x, 10, 14, 11, 2);
    b.rect(x + 1, 11, 12, 9, 0);
    b.rect(x + 2, 11, 3, 1, 1); // glint
  }
  b.rect(110, 9, 11, 22, 2); // door
  b.rect(111, 10, 9, 20, 1);
  b.rect(112, 12, 7, 6, 0);
  b.set(118, 21, 3);
  b.rect(4, 24, 105, 2, 3); // livery stripe
  b.rect(4, 27, 105, 1, 2);
  b.rect(8, 32, 112, 3, 2); // undercarriage
  for (const wx of [20, 40, 88, 108]) {
    b.ellipse(wx, 38, 5, 5, 2);
    b.ellipse(wx, 38, 3, 3, 0);
    const a = wheelPhase * Math.PI * 0.5;
    b.line(wx - Math.round(Math.cos(a) * 3), 38 - Math.round(Math.sin(a) * 3), wx + Math.round(Math.cos(a) * 3), 38 + Math.round(Math.sin(a) * 3), 2);
    b.set(wx, 38, 3);
  }
  b.rect(14, 37, 30, 1, 3); // coupling rod
  b.rect(82, 37, 30, 1, 3);
  return b.toRows();
}

